// ─── Nonce registry — prevents nonce reuse within a process lifetime ──────────

/// Process-global set of base nonces used in this session.
/// Probability of a legitimate collision on 96-bit random nonces is ~1/2^96.
/// If we ever see a repeat (hardware RNG failure), we abort immediately.
static NONCE_REGISTRY: OnceLock<DashSet<[u8; 12]>> = OnceLock::new();

fn nonce_registry() -> &'static DashSet<[u8; 12]> {
    NONCE_REGISTRY.get_or_init(DashSet::new)
}

/// Registers a nonce. Returns Err if the nonce was already used (RNG failure).
fn register_nonce(nonce: [u8; 12]) -> Result<(), String> {
    if !nonce_registry().insert(nonce) {
        // This should be cryptographically impossible with a healthy OsRng.
        return Err(
            "CRITICAL: Nonce collision detected — possible RNG failure. Operation aborted."
                .to_string(),
        );
    }
    Ok(())
}

// ─── Header constants ─────────────────────────────────────────────────────────

const AEGIS_MAGIC: &[u8; 6] = b"AEGIS4";
const VERSION_MAJOR: u8     = 0x01;
const VERSION_MINOR: u8     = 0x00;
const HEADER_SIZE:   u64    = 96;

/// HKDF info labels — never change these; changing them breaks decryption.
const KVT_INFO:        &[u8] = b"aegis-kvt-v1";
const HEADER_MAC_INFO: &[u8] = b"aegis-header-mac-v1";

/// Algorithm identifiers for cryptographic agility.
#[repr(u8)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum AlgoId {
    Aes256GcmBe32   = 0x01,
    ChaCha20Poly1305 = 0x02, // reserved for future implementation
}

impl TryFrom<u8> for AlgoId {
    type Error = String;
    fn try_from(v: u8) -> Result<Self, Self::Error> {
        match v {
            0x01 => Ok(AlgoId::Aes256GcmBe32),
            0x02 => Err(
                "ChaCha20-Poly1305 vaults require Aegis Vault v5+.".to_string()
            ),
            other => Err(format!(
                "Unknown algorithm 0x{other:02X}. Please upgrade Aegis Vault."
            )),
        }
    }
}

// ─── KDF / streaming constants ────────────────────────────────────────────────

const ARGON2_MEM_KIB:  u32   = 64 * 1024; // 64 MiB — OWASP 2023 interactive
const ARGON2_ITERS:    u32   = 3;
const ARGON2_PARALLEL: u32   = 4;
const BUFFER_SIZE:     usize = 256 * 1024; // 256 KiB per streaming chunk

// ─── Secure key material ──────────────────────────────────────────────────────

/// 32-byte master key. Zeroed on drop. Never Clone, never Debug.
#[derive(Zeroize, ZeroizeOnDrop)]
struct MasterKey([u8; 32]);

impl MasterKey {
    /// Derives a MasterKey from password + salt via Argon2id.
    /// Takes `password` by reference — no secret material is cloned.
    fn derive(
        password: &[u8],
        salt:     &[u8],
        mem_kib:  u32,
        iters:    u32,
        parallel: u32,
    ) -> Result<Self, String> {
        let params = Params::new(mem_kib, iters, parallel, Some(32))
            .map_err(|e| format!("Argon2 params error: {e}"))?;
        let argon2 = Argon2::new(
            argon2::Algorithm::Argon2id,
            Argon2Version::V0x13,
            params,
        );
        let mut key = [0u8; 32];
        argon2
            .hash_password_into(password, salt, &mut key)
            .map_err(|e| format!("Key derivation failed: {e}"))?;
        Ok(MasterKey(key))
    }

    /// Derives the 32-byte Key-Verification Tag via HKDF-SHA256.
    /// Stored in the header for instant password validation.
    fn derive_kvt(&self) -> [u8; 32] {
        let hk = Hkdf::<Sha256>::new(None, &self.0);
        let mut kvt = [0u8; 32];
        hk.expand(KVT_INFO, &mut kvt)
            .expect("HKDF KVT expand: output length always valid");
        kvt
    }

    /// Derives a 32-byte subkey for header MAC via HKDF-SHA256.
    fn derive_header_mac_key(&self) -> [u8; 32] {
        let hk = Hkdf::<Sha256>::new(None, &self.0);
        let mut k = [0u8; 32];
        hk.expand(HEADER_MAC_INFO, &mut k)
            .expect("HKDF header-mac expand: output length always valid");
        k
    }
}

// ─── Header MAC helpers ───────────────────────────────────────────────────────

type HmacSha256 = Hmac<Sha256>;

/// Computes HMAC-SHA256 over `data` using `key`, returns first 4 bytes.
/// 32-bit truncation: forgery probability = 1/2^32 per attempt.
/// Full Argon2id cost already makes brute-force infeasible regardless.
fn compute_header_mac(key: &[u8; 32], data: &[u8]) -> [u8; 4] {
    let mut mac = HmacSha256::new_from_slice(key)
        .expect("HMAC accepts any key length");
    mac.update(data);
    let result = mac.finalize().into_bytes();
    let mut out = [0u8; 4];
    out.copy_from_slice(&result[..4]);
    out
}

// ─── File locking (cross-platform) ───────────────────────────────────────────

/// Acquires an exclusive advisory lock on a std::fs::File.
/// Uses fcntl(LOCK_EX) on Unix, LockFileEx on Windows.
/// Returns immediately if the file is already locked (Err).
#[cfg(unix)]
fn lock_file_exclusive(file: &std::fs::File) -> Result<(), String> {
    use std::os::unix::io::AsRawFd;
    let fd = file.as_raw_fd();
    let ret = unsafe { libc::flock(fd, libc::LOCK_EX | libc::LOCK_NB) };
    if ret != 0 {
        let err = std::io::Error::last_os_error();
        return Err(format!(
            "Cannot lock file — another process may be using it: {err}"
        ));
    }
    Ok(())
}

#[cfg(unix)]
fn unlock_file(file: &std::fs::File) {
    use std::os::unix::io::AsRawFd;
    unsafe { libc::flock(file.as_raw_fd(), libc::LOCK_UN) };
}

#[cfg(windows)]
fn lock_file_exclusive(file: &std::fs::File) -> Result<(), String> {
    use std::os::windows::io::AsRawHandle;
    use windows_sys::Win32::Storage::FileSystem::{
        LockFileEx, LOCKFILE_EXCLUSIVE_LOCK, LOCKFILE_FAIL_IMMEDIATELY,
    };
    use windows_sys::Win32::System::IO::OVERLAPPED;
    let handle = file.as_raw_handle() as windows_sys::Win32::Foundation::HANDLE;
    let mut overlapped = unsafe { std::mem::zeroed::<OVERLAPPED>() };
    let ret = unsafe {
        LockFileEx(
            handle,
            LOCKFILE_EXCLUSIVE_LOCK | LOCKFILE_FAIL_IMMEDIATELY,
            0, u32::MAX, u32::MAX,
            &mut overlapped,
        )
    };
    if ret == 0 {
        return Err("Cannot lock file — another process may be using it.".to_string());
    }
    Ok(())
}

#[cfg(windows)]
fn unlock_file(_file: &std::fs::File) {
    // Windows releases locks automatically on file handle close.
}

// Stub for non-Unix non-Windows (WASM, etc.) — no locking available.
#[cfg(not(any(unix, windows)))]
fn lock_file_exclusive(_file: &std::fs::File) -> Result<(), String> { Ok(()) }
#[cfg(not(any(unix, windows)))]
fn unlock_file(_file: &std::fs::File) {}

