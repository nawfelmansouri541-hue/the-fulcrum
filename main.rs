// ─── GUI state ────────────────────────────────────────────────────────────────

struct AegisVaultGui {
    password:       String,
    file_path:      String,
    status_message: String,
    progress:       f32,
    is_processing:  bool,
    progress_rx:    Option<tokio::sync::mpsc::Receiver<ProgressUpdate>>,
}

#[derive(Debug, Clone)]
enum Message {
    PasswordChanged(String),
    FilePathChanged(String),
    EncryptPressed,
    DecryptPressed,
    ProgressTick,
    OperationFinished,
}

impl Application for AegisVaultGui {
    type Executor = executor::Default;
    type Message  = Message;
    type Theme    = Theme;
    type Flags    = ();

    fn new(_flags: ()) -> (Self, Command<Message>) {
        (
            AegisVaultGui {
                password:       String::new(),
                file_path:      String::new(),
                status_message: "Ready — awaiting your command.".to_string(),
                progress:       0.0,
                is_processing:  false,
                progress_rx:    None,
            },
            Command::none(),
        )
    }

    fn title(&self) -> String {
        "🛡️  Aegis Sovereign Vault  v4".to_string()
    }

    fn update(&mut self, message: Message) -> Command<Message> {
        match message {
            Message::PasswordChanged(p) => { self.password  = p; Command::none() }
            Message::FilePathChanged(p) => { self.file_path = p; Command::none() }

            Message::EncryptPressed => {
                if let Some(err) = self.validate_inputs() {
                    self.status_message = err;
                    return Command::none();
                }
                self.begin_operation(
                    "🔒 Deriving Argon2id key — this takes a few seconds…"
                );
                let (tx, rx) = tokio::sync::mpsc::channel::<ProgressUpdate>(128);
                self.progress_rx = Some(rx);
                let secret = Arc::new(SecretVec::new(self.password.as_bytes().to_vec()));
                let path   = self.file_path.clone();
                Command::perform(
                    async move {
                        let result = async_encrypt(secret, path, tx.clone()).await;
                        let _ = tx.send(ProgressUpdate::Done(result)).await;
                    },
                    |_| Message::OperationFinished,
                )
            }

            Message::DecryptPressed => {
                if let Some(err) = self.validate_inputs() {
                    self.status_message = err;
                    return Command::none();
                }
                self.begin_operation(
                    "🔓 Verifying password — this takes a few seconds…"
                );
                let (tx, rx) = tokio::sync::mpsc::channel::<ProgressUpdate>(128);
                self.progress_rx = Some(rx);
                let secret = Arc::new(SecretVec::new(self.password.as_bytes().to_vec()));
                let path   = self.file_path.clone();
                Command::perform(
                    async move {
                        let result = async_decrypt(secret, path, tx.clone()).await;
                        let _ = tx.send(ProgressUpdate::Done(result)).await;
                    },
                    |_| Message::OperationFinished,
                )
            }

            Message::ProgressTick => {
                if let Some(rx) = &mut self.progress_rx {
                    loop {
                        match rx.try_recv() {
                            Ok(ProgressUpdate::Percent(p)) => {
                                self.progress = p;
                                let stage = if p < 6.0 {
                                    "Deriving key (Argon2id)…"
                                } else {
                                    "Streaming & authenticating…"
                                };
                                self.status_message = format!("{stage}  {p:.0}%");
                            }
                            Ok(ProgressUpdate::Done(result)) => {
                                self.is_processing = false;
                                self.progress_rx   = None;
                                match result {
                                    Ok(msg)  => {
                                        self.progress       = 100.0;
                                        self.status_message = format!("✅ {msg}");
                                    }
                                    Err(err) => {
                                        self.progress       = 0.0;
                                        self.status_message = format!("🚨 {err}");
                                    }
                                }
                                break;
                            }
                            Err(_) => break,
                        }
                    }
                }
                Command::none()
            }

            Message::OperationFinished => Command::none(),
        }
    }

    fn subscription(&self) -> iced::Subscription<Message> {
        if self.is_processing {
            iced::time::every(std::time::Duration::from_millis(33))
                .map(|_| Message::ProgressTick)
        } else {
            iced::Subscription::none()
        }
    }

    fn view(&self) -> Element<Message> {
        let pass_input = text_input(
            "Master password (≥ 12 chars)…",
            &self.password,
        )
        .on_input(Message::PasswordChanged)
        .password()
        .padding(12);

        let path_input = text_input("Absolute file path…", &self.file_path)
            .on_input(Message::FilePathChanged)
            .padding(12);

        let action_row: Element<Message> = if self.is_processing {
            text(format!("⏳  {}", self.status_message)).size(15).into()
        } else {
            row![
                button("🔒  Encrypt & Shred")
                    .on_press(Message::EncryptPressed)
                    .padding(14),
                button("🔓  Decrypt Vault")
                    .on_press(Message::DecryptPressed)
                    .padding(14),
            ]
            .spacing(20)
            .into()
        };

        let ssd_notice = text(
            "⚠  SSD/NVMe: secure-shred is best-effort. \
             Use full-disk encryption for complete protection."
        )
        .size(11);

        let content = column![
            text("🛡️  AEGIS SOVEREIGN VAULT  v4").size(26),
            text(
                "AES-256-GCM  •  Argon2id  •  Header MAC  \
                 •  KVT Fast-Auth  •  Nonce Registry  •  File Lock"
            ).size(11),
            pass_input,
            path_input,
            action_row,
            progress_bar(0.0..=100.0, self.progress),
            text(format!("{:.0}%", self.progress)).size(12),
            text(&self.status_message).size(14),
            ssd_notice,
        ]
        .spacing(18)
        .max_width(720);

        container(content)
            .width(Length::Fill)
            .height(Length::Fill)
            .center_x()
            .center_y()
            .padding(48)
            .into()
    }

    fn theme(&self) -> Theme { Theme::Dark }
}

// ─── GUI helpers ──────────────────────────────────────────────────────────────

impl AegisVaultGui {
    fn validate_inputs(&self) -> Option<String> {
        if self.password.len() < 12 {
            return Some("🚨 Password must be at least 12 characters.".to_string());
        }
        if self.file_path.trim().is_empty() {
            return Some("🚨 Please enter a file path.".to_string());
        }
        None
    }

    fn begin_operation(&mut self, msg: &str) {
        self.is_processing  = true;
        self.progress       = 0.0;
        self.status_message = msg.to_string();
    }
}
