// ─── Encryption ───────────────────────────────────────────────────────────────

async fn async_encrypt(
    password:    Arc<SecretVec<u8>>,
    path_str:    String,
    progress_tx: tokio::sync::mpsc::Sender<ProgressUpdate>,
) -> Result<String, String> {
    let input_path = PathBuf::from(&path_str);

    // ── 1. open + lock source file ───────────────────────────────────────────
    //    We open with std::fs first (for locking), then hand to tokio.
    let std_src = std::fs::OpenOptions::new()
        .read(true)
        .open(&input_path)
        .map_err(|e| format!("Cannot open source file: {e}"))?;
    lock_file_exclusive(&std_src)
        .map_err(|e| format!("Source file lock failed: {e}"))?;

    let file_size = std_src
        .metadata()
        .map_err(|e| format!("Cannot read metadata: {e}"))?
        .len();

    // Convert to tokio::fs::File for async I/O
    let src = File::from_std(std_src);
    let mut reader = BufReader::new(src);

    // ── 2. output path + lock output file ───────────────────────────────────
    let mut raw_out = input_path.as_os_str().to_owned();
    raw_out.push(".aegis");
    let output_path = PathBuf::from(raw_out);

    let std_dst = std::fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .open(&output_path)
        .map_err(|e| format!("Cannot create output file: {e}"))?;
    lock_file_exclusive(&std_dst)
        .map_err(|e| format!("Output file lock failed: {e}"))?;
    let dst = File::from_std(std_dst);
    let mut writer = BufWriter::new(dst);

    // ── 3. generate random salt + nonce (OsRng — best available entropy) ────
    let mut salt  = [0u8; 16];
    let mut nonce = [0u8; 12];
    OsRng.fill_bytes(&mut salt);
    OsRng.fill_bytes(&mut nonce);

    // ── 4. nonce uniqueness check ────────────────────────────────────────────
    register_nonce(nonce)?;

    // ── 5. derive master key  (blocking — Argon2id is CPU/memory heavy) ─────
    let pw_arc    = Arc::clone(&password);
    let salt_copy = salt;
    let key = tokio::task::spawn_blocking(move || {
        MasterKey::derive(
            pw_arc.expose_secret(),
            &salt_copy,
            ARGON2_MEM_KIB,
            ARGON2_ITERS,
            ARGON2_PARALLEL,
        )
    })
    .await
    .map_err(|e| format!("KDF thread panicked: {e}"))??;

    let _ = progress_tx.send(ProgressUpdate::Percent(5.0)).await;

    // ── 6. derive KVT + header MAC key ──────────────────────────────────────
    let kvt            = key.derive_kvt();
    let header_mac_key = key.derive_header_mac_key();

    // ── 7. build header bytes 0..92 (before MAC field) ──────────────────────
    let mut header = [0u8; 96];
    header[0..6].copy_from_slice(AEGIS_MAGIC);
    header[6]   = VERSION_MAJOR;
    header[7]   = VERSION_MINOR;
    header[8]   = AlgoId::Aes256GcmBe32 as u8;
    // bytes 9..16 = reserved zeros
    header[16..32].copy_from_slice(&salt);
    header[32..44].copy_from_slice(&nonce);
    header[44..48].copy_from_slice(&ARGON2_MEM_KIB.to_be_bytes());
    header[48..52].copy_from_slice(&ARGON2_ITERS.to_be_bytes());
    header[52..56].copy_from_slice(&ARGON2_PARALLEL.to_be_bytes());
    header[56..60].copy_from_slice(&(BUFFER_SIZE as u32).to_be_bytes());
    header[60..92].copy_from_slice(&kvt);
    // bytes 92..96 = header MAC (filled next)
    let mac = compute_header_mac(&header_mac_key, &header[0..92]);
    header[92..96].copy_from_slice(&mac);

    writer.write_all(&header).await.map_err(|e| e.to_string())?;

    // ── 8. stream-encrypt payload ────────────────────────────────────────────
    let aead = Aes256Gcm::new_from_slice(&key.0)
        .map_err(|_| "Cipher init failed.".to_string())?;
    let mut encryptor = EncryptorBE32::from_aead(aead, (&nonce).into());

    let mut buf        = vec![0u8; BUFFER_SIZE];
    let mut bytes_done = 0u64;

    loop {
        let n = reader
            .read(&mut buf)
            .await
            .map_err(|e| format!("Read error: {e}"))?;
        if n == 0 { break; }

        bytes_done += n as u64;
        let is_last = bytes_done >= file_size;

        let ct = if is_last {
            encryptor.encrypt_last(&buf[..n])
                .map_err(|_| "Encryption finalisation failed.".to_string())?
        } else {
            encryptor.encrypt_next(&buf[..n])
                .map_err(|_| "Encryption chunk failed.".to_string())?
        };

        writer.write_all(&ct).await.map_err(|e| e.to_string())?;

        let pct = 5.0 + (bytes_done as f32 / file_size.max(1) as f32) * 95.0;
        let _ = progress_tx.send(ProgressUpdate::Percent(pct)).await;

        if is_last { break; }
    }

    writer.flush().await.map_err(|e| e.to_string())?;

    // ── 9. secure-delete original ────────────────────────────────────────────
    //    The source std::fs::File (still locked) is passed to secure_delete.
    //    The lock is released inside secure_delete just before unlink.
    secure_delete(&input_path).await?;

    Ok(format!("Vault sealed → {:?}", output_path))
}

// ─── Decryption ───────────────────────────────────────────────────────────────

async fn async_decrypt(
    password:    Arc<SecretVec<u8>>,
    path_str:    String,
    progress_tx: tokio::sync::mpsc::Sender<ProgressUpdate>,
) -> Result<String, String> {
    let input_path = PathBuf::from(&path_str);

    // ── 1. open + lock vault file ────────────────────────────────────────────
    let std_src = std::fs::OpenOptions::new()
        .read(true)
        .open(&input_path)
        .map_err(|e| format!("Cannot open vault file: {e}"))?;
    lock_file_exclusive(&std_src)
        .map_err(|e| format!("Vault file lock failed: {e}"))?;

    let total_size = std_src
        .metadata()
        .map_err(|e| format!("Cannot read metadata: {e}"))?
        .len();

    let src = File::from_std(std_src);
    let mut reader = BufReader::new(src);

    // ── 2. read full header (96 bytes) ───────────────────────────────────────
    let mut header = [0u8; 96];
    reader
        .read_exact(&mut header)
        .await
        .map_err(|_| "File too small to be an Aegis vault.".to_string())?;

    // ── 3. validate magic ────────────────────────────────────────────────────
    if &header[0..6] != AEGIS_MAGIC {
        return Err("Not an Aegis vault file (bad magic bytes).".to_string());
    }

    // ── 4. validate version ──────────────────────────────────────────────────
    let file_major = header[6];
    let file_minor = header[7];
    if file_major != VERSION_MAJOR {
        return Err(format!(
            "Unsupported vault version {file_major}.{file_minor}. \
             Please upgrade Aegis Vault."
        ));
    }
    // Minor version: forward-compatible — we accept any minor version
    // as long as the major matches.

    // ── 5. validate algo_id ──────────────────────────────────────────────────
    let _algo = AlgoId::try_from(header[8])?;

    // ── 6. parse header fields ───────────────────────────────────────────────
    let salt:     [u8; 16] = header[16..32].try_into().unwrap();
    let nonce:    [u8; 12] = header[32..44].try_into().unwrap();
    let mem_kib  = u32::from_be_bytes(header[44..48].try_into().unwrap());
    let iters    = u32::from_be_bytes(header[48..52].try_into().unwrap());
    let parallel = u32::from_be_bytes(header[52..56].try_into().unwrap());
    let chunk_sz = u32::from_be_bytes(header[56..60].try_into().unwrap()) as usize;
    let kvt_stored: [u8; 32] = header[60..92].try_into().unwrap();
    let mac_stored: [u8; 4]  = header[92..96].try_into().unwrap();

    // Sanity-check chunk size to prevent memory exhaustion attacks
    if chunk_sz == 0 || chunk_sz > 16 * 1024 * 1024 {
        return Err("Vault header contains invalid chunk size.".to_string());
    }

    // ── 7. derive master key (blocking) ──────────────────────────────────────
    let pw_arc    = Arc::clone(&password);
    let salt_copy = salt;
    let key = tokio::task::spawn_blocking(move || {
        MasterKey::derive(pw_arc.expose_secret(), &salt_copy, mem_kib, iters, parallel)
    })
    .await
    .map_err(|e| format!("KDF thread panicked: {e}"))??;

    // ── 8. FAIL-FAST: verify KVT (constant-time) ─────────────────────────────
    //    This validates the password in O(1) before any payload I/O.
    let kvt_derived = key.derive_kvt();
    if kvt_derived.ct_eq(&kvt_stored).unwrap_u8() != 1 {
        return Err("Authentication failed — wrong password or corrupted vault.".to_string());
    }

    // ── 9. ANTI-TAMPER: verify header MAC (constant-time) ────────────────────
    //    Protects against downgrade attacks, parameter manipulation, etc.
    //    An attacker who changes algo_id, KDF params, or nonce in the header
    //    will be detected here.
    let header_mac_key = key.derive_header_mac_key();
    let mac_computed   = compute_header_mac(&header_mac_key, &header[0..92]);
    if mac_computed.ct_eq(&mac_stored).unwrap_u8() != 1 {
        return Err(
            "Header integrity check failed — vault may have been tampered with.".to_string()
        );
    }

    let _ = progress_tx.send(ProgressUpdate::Percent(5.0)).await;

    // ── 10. build output path ─────────────────────────────────────────────────
    let output_path = if input_path.extension().map_or(false, |e| e == "aegis") {
        input_path.with_extension("")
    } else {
        input_path.with_extension("decrypted")
    };

    let std_dst = std::fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .open(&output_path)
        .map_err(|e| format!("Cannot create output file: {e}"))?;
    lock_file_exclusive(&std_dst)
        .map_err(|e| format!("Output file lock failed: {e}"))?;

    let dst = File::from_std(std_dst);
    let mut writer = BufWriter::new(dst);

    // ── 11. stream-decrypt payload ────────────────────────────────────────────
    let aead = Aes256Gcm::new_from_slice(&key.0)
        .map_err(|_| "Cipher init failed.".to_string())?;
    let mut decryptor = DecryptorBE32::from_aead(aead, (&nonce).into());

    let ct_chunk     = chunk_sz + 16; // ciphertext = plaintext + 16-byte GCM tag
    let mut buf      = vec![0u8; ct_chunk];
    let mut remaining    = total_size.saturating_sub(HEADER_SIZE);
    let payload_total = remaining;

    loop {
        let to_read = (remaining as usize).min(ct_chunk);
        if to_read == 0 { break; }

        reader
            .read_exact(&mut buf[..to_read])
            .await
            .map_err(|e| format!("Read error: {e}"))?;
        remaining -= to_read as u64;

        let plaintext = if remaining == 0 {
            decryptor.decrypt_last(&buf[..to_read])
                .map_err(|_| "Payload authentication failed — vault is corrupted.".to_string())?
        } else {
            decryptor.decrypt_next(&buf[..to_read])
                .map_err(|_| "Chunk authentication failed — vault is corrupted.".to_string())?
        };

        writer.write_all(&plaintext).await.map_err(|e| e.to_string())?;

        let done = payload_total.saturating_sub(remaining);
        let pct  = 5.0 + (done as f32 / payload_total.max(1) as f32) * 95.0;
        let _ = progress_tx.send(ProgressUpdate::Percent(pct)).await;
    }

    writer.flush().await.map_err(|e| e.to_string())?;

    Ok(format!("Vault opened → {:?}", output_path))
}

// ─── Secure delete ────────────────────────────────────────────────────────────

/// Best-effort secure erasure with honest SSD limitations (see module docs).
///
/// Steps:
///  1. Open with exclusive lock (prevents concurrent reads during overwrite)
///  2. 3-pass overwrite: random / zeros / random — each followed by sync_all
///  3. Truncate to zero + sync_all (clears some filesystem size metadata)
///  4. Unlock + remove_file
///
/// This is maximally effective on HDDs and on SSDs that do not expose a
/// dedicated SECURE ERASE command to userspace (virtually all consumer drives).
async fn secure_delete(path: &PathBuf) -> Result<(), String> {
    let file_size = tokio::fs::metadata(path)
        .await
        .map_err(|e| format!("secure_delete — metadata: {e}"))?
        .len() as usize;

    // We need a std::fs::File to call lock_file_exclusive.
    let std_f = std::fs::OpenOptions::new()
        .write(true)
        .open(path)
        .map_err(|e| format!("secure_delete — open: {e}"))?;
    lock_file_exclusive(&std_f)
        .map_err(|e| format!("secure_delete — lock: {e}"))?;

    // Three-pass overwrite
    let pass_count = 3usize;
    for pass in 0..pass_count {
        let mut f = OpenOptions::new()
            .write(true)
            .open(path)
            .await
            .map_err(|e| format!("secure_delete pass {pass} — open: {e}"))?;

        let mut buf      = vec![0u8; BUFFER_SIZE.min(file_size.max(1))];
        let mut written  = 0usize;

        while written < file_size {
            let chunk = (file_size - written).min(BUFFER_SIZE);
            if pass == 1 {
                // Pass 2: zeros
                buf[..chunk].iter_mut().for_each(|b| *b = 0);
            } else {
                // Pass 1 + 3: CSPRNG random bytes
                OsRng.fill_bytes(&mut buf[..chunk]);
            }
            f.write_all(&buf[..chunk])
                .await
                .map_err(|e| format!("secure_delete pass {pass} — write: {e}"))?;
            written += chunk;
        }

        // sync_all(): flushes OS buffers to storage hardware.
        // On HDDs: reaches magnetic platter.
        // On SSDs: reaches flash controller (physical location is controller's choice).
        f.sync_all()
            .await
            .map_err(|e| format!("secure_delete pass {pass} — fsync: {e}"))?;
    }

    // Truncate to zero: clears filesystem-level size metadata.
    {
        let f = OpenOptions::new()
            .write(true)
            .open(path)
            .await
            .map_err(|e| format!("secure_delete — open for truncate: {e}"))?;
        f.set_len(0)
            .await
            .map_err(|e| format!("secure_delete — truncate: {e}"))?;
        f.sync_all()
            .await
            .map_err(|e| format!("secure_delete — fsync truncate: {e}"))?;
    }

    // Release OS lock, then unlink.
    unlock_file(&std_f);
    tokio::fs::remove_file(path)
        .await
        .map_err(|e| format!("secure_delete — unlink: {e}"))?;

    Ok(())
}

