// =============================================================================
//  AEGIS SOVEREIGN VAULT — v4.0  |  Audit-Grade Production Implementation
// =============================================================================
//
//  THREAT MODEL & SECURITY GUARANTEES
//  ────────────────────────────────────
//  1. CONFIDENTIALITY
//     AES-256-GCM streaming AEAD — IND-CCA2 secure, authenticated per-chunk.
//     Each chunk carries its own 16-byte GCM tag; truncation is detected.
//
//  2. INTEGRITY / ANTI-TAMPER
//     • Per-chunk GCM tags: detect any bit-flip in the ciphertext.
//     • Header AEAD MAC: the entire header (salt, nonce, KDF params, version,
//       algo_id) is authenticated with a dedicated HKDF-derived subkey.
//       Any tampering with header fields is detected before decryption begins.
//     • KVT (Key-Verification Tag): instant password check in O(1), constant-time.
//
//  3. NONCE-REUSE PREVENTION
//     • 96-bit random nonce generated by OsRng (CSPRNG) per operation.
//     • Nonce uniqueness probability over 2^32 files: P(collision) < 2^{-32}
//       (birthday bound on 96-bit space with 32-bit file count).
//     • Additionally, the EncryptorBE32 API internally increments a 32-bit
//       big-endian counter suffix per chunk, so the full per-chunk nonce is:
//         base_nonce[0..8] || counter[0..4]
//       making per-chunk nonce reuse impossible within a single file.
//     • A per-process nonce registry (DashMap) is kept in-memory.
//       If the same base nonce ever appears twice in one process lifetime
//       (probability ~1/2^96 per run), the operation is aborted.
//
//  4. FILE LOCKING
//     • Source file is locked exclusively (fcntl LOCK_EX / LockFileEx on Win)
//       before any I/O begins, and released only after secure_delete completes.
//     • Output file is locked exclusively for the duration of the write.
//     • Prevents TOCTOU races and concurrent corruption by other processes.
//
//  5. PROTOCOL VERSIONING & CRYPTOGRAPHIC AGILITY
//     • 2-byte (major.minor) version in header, not 1-byte.
//     • AlgoId enum covers current + future ciphers (AES-256-GCM, ChaCha20).
//     • Header is fully authenticated: a MAC over all header fields means
//       downgrade attacks (an attacker changing algo_id or KDF params) are
//       detected immediately.
//
//  6. SECURE ERASURE — HONEST THREAT MODEL
//     The secure_delete() function performs the maximum achievable at
//     OS/userspace level:
//       • Exclusive file lock (prevents concurrent reads during overwrite)
//       • Pass 1: random bytes   + sync_all (fsync)
//       • Pass 2: zero bytes     + sync_all
//       • Pass 3: random bytes   + sync_all
//       • set_len(0)             + sync_all  (clear filesystem size metadata)
//       • remove_file (unlink)
//     HONEST LIMITATION: On SSDs/NVMe/eMMC with wear-levelling, the flash
//     controller decides physical write locations. OS-level overwrites do NOT
//     guarantee erasure of all physical copies. The only complete solution
//     is full-disk encryption (LUKS, BitLocker, FileVault) so the raw flash
//     holds only ciphertext. This limitation is surfaced to the user in the GUI.
//
//  HEADER FORMAT  v4.0  (total = 96 bytes)
//  ─────────────────────────────────────────
//   Offset  Len   Field
//   ──────  ───   ────────────────────────────────────────────────────────
//    0       6    Magic           b"AEGIS4"
//    6       1    Version major   u8  (currently 0x01)
//    7       1    Version minor   u8  (currently 0x00)
//    8       1    AlgoId          u8  (0x01=AES-256-GCM, 0x02=ChaCha20)
//    9       7    Reserved        [u8;7] — must be 0x00 (future flags)
//   16      16    Salt            random, Argon2id input
//   32      12    Nonce           random, AES-GCM-BE32 base nonce
//   44       4    argon2_mem_kib  u32 big-endian
//   48       4    argon2_iters    u32 big-endian
//   52       4    argon2_par      u32 big-endian
//   56       4    chunk_size      u32 big-endian (BUFFER_SIZE at encryption time)
//   60      32    KVT             HKDF-SHA256(master_key, "aegis-kvt-v1")
//   92       4    Header MAC      first 4 bytes of HMAC-SHA256(header_key, header[0..92])
//                                 (full 32-byte MAC is overkill for a header; 32-bit
//                                  MAC gives 1/2^32 forgery probability — sufficient
//                                  when Argon2id already costs seconds to verify)
//  ──────  ───
//   96      TOTAL
//
// =============================================================================

